import { CLASS_INFO } from './incidents'
import { CHECKLISTS, LAYER_LABEL, stepKey } from '../catalog/checklists'
import type { CheckStep } from '../catalog/checklists'
import { RUNBOOKS, type Runbook } from '../catalog/runbooks'
import type { RunbookId } from '../catalog/runbooks'
import { SUB_LABEL, VERDICT_RULE, type Chain } from './verdict'

// The clock of each ticked step: the step key, and the time that the session recorded. The URL holds which
// steps are done; this holds when, and it does not travel with the link.
export type TickClock = Record<string, string>

const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

// The incident timeline: the verdict, the chain, and the checklist with the ticked steps. The Markdown is the
// skeleton of the postmortem of M7: the scribe adds the human actions and the clocks.
export function timelineMarkdown(chain: Chain, runbook: Runbook | null, steps: CheckStep[], done: string[], at: TickClock): string {
  const v = chain.verdict
  const out: string[] = []
  out.push(`# Incident timeline: ${chain.label}`, '')
  out.push(`Start: ${chain.start}. Events: ${chain.rows.length}. Generated by the AI Factory Explorer.`, '')
  out.push('## Verdict', '')
  out.push('| Field | Value |', '| --- | --- |')
  out.push(`| terminal_state | ${v.terminal ?? 'no state change'} |`)
  out.push(`| sub_domain | ${SUB_LABEL[v.sub]} |`)
  out.push(`| failure class | ${v.cls ? CLASS_INFO[v.cls].label : 'none: the evidence does not name one'} |`)
  out.push(`| responsible node | ${v.node ?? 'none'} |`)
  out.push(`| confidence | ${v.confidence} |`)
  out.push(`| votes | hardware ${v.votes.hardware}, system software ${v.votes.system_software} |`, '')
  out.push(v.why, '')
  out.push('## Chain', '')
  out.push('| # | Time | Source | Event | Class | Row |', '| --- | --- | --- | --- | --- | --- |')
  for (const r of chain.rows) {
    const cls = r.cls ? `${CLASS_INFO[r.cls].label} (${SUB_LABEL[CLASS_INFO[r.cls].sub]})` : 'context or symptom'
    out.push(`| ${r.i + 1} | ${r.clock} | ${r.src} | ${cell(r.text)}${r.note ? ` (${cell(r.note)})` : ''} | ${cell(cls)} | ${r.row ?? ''} |`)
  }
  out.push('')
  if (runbook) {
    const ticked = steps.filter((s) => done.includes(stepKey(runbook.id, s.n)))
    out.push(`## Runbook checklist: ${runbook.id} (${ticked.length} of ${steps.length})`, '')
    out.push('| Time | Step | Layer | Who | Command | Expected | Done | Evidence |', '| --- | --- | --- | --- | --- | --- | --- | --- |')
    for (const s of steps) {
      const key = stepKey(runbook.id, s.n)
      const isDone = done.includes(key)
      out.push(
        `| ${at[key] ?? 'not recorded'} | ${s.n} | ${s.layer ? LAYER_LABEL[s.layer] : 'none'} | ${s.who} | ${cell(s.command)} | ${cell(s.expected)} | ${isDone ? 'yes' : 'no'} | ${cell(s.says)} |`,
      )
    }
    out.push('')
  }
  out.push('## How the Explorer made this', '')
  out.push(`The collapse rule: ${VERDICT_RULE}`, '')
  out.push('The actor of each tick is the operator of this session. A step with no recorded time was checked before the clock of the session recorded it.', '')
  out.push('The events are the evidence of the incident; the verdict is the summary. The Explorer does not probe the hardware, and it does not make the replace or return-to-service decision.', '')
  return out.join('\n')
}

// The file name of the export: the incident, and the runbook when a checklist is open.
export const timelineName = (chain: Chain, runbook: Runbook | null): string =>
  `incident-${chain.id}${runbook ? `-${runbook.id.toLowerCase()}` : ''}-timeline.md`

// The export of the current diagnosis: the chain, and the open checklist with its ticked steps.
export function timelineOf(chain: Chain, diag: { checklist: RunbookId | null; done: string[]; at: TickClock }): { name: string; text: string } {
  const runbook = diag.checklist ? (RUNBOOKS.find((r) => r.id === diag.checklist) ?? null) : null
  const steps: CheckStep[] = runbook ? (CHECKLISTS[runbook.id] ?? []) : []
  return { name: timelineName(chain, runbook), text: timelineMarkdown(chain, runbook, steps, diag.done, diag.at) }
}
